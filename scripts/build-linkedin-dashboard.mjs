import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const sources = [
  "supabase/functions/_shared/linkedin-job-url.ts",
  "supabase/functions/_shared/linkedin-job-details.ts",
  "supabase/functions/_shared/linkedin-job-handler.ts",
  "supabase/functions/linkedin-job/index.ts",
];
const allowed = new Set([
  "./linkedin-job-url.ts",
  "./linkedin-job-details.ts",
  "../_shared/linkedin-job-handler.ts",
  "@supabase/supabase-js",
]);
const imports = JSON.parse(
  await readFile(new URL("supabase/functions/deno.json", root), "utf8"),
).imports;
const pieces = [];
for (const path of sources) {
  let text = await readFile(new URL(path, root), "utf8");
  text = text
    .replace(
      /^import\s+[\s\S]*?from\s+["']([^"']+)["'];?\s*$/gm,
      (statement, name) => {
        if (!allowed.has(name))
          throw new Error(`Unsupported dashboard import: ${name}`);
        return "";
      },
    )
    .replace(/^export\s+/gm, "");
  pieces.push(`// ${path}\n${text.trim()}`);
}
const output = `// Generated by node scripts/build-linkedin-dashboard.mjs.\n// Paste this entire file into index.ts in Supabase's Edge Function editor.\n// Function name: quick-responder. JWT is verified inside the handler.\nimport { createClient } from ${JSON.stringify(imports["@supabase/supabase-js"])};\n\n${pieces.join("\n\n")}\n`;
await writeFile(new URL("docs/linkedin-job-dashboard.txt", root), output);
console.log("Generated docs/linkedin-job-dashboard.txt");
